export const getCategoryLabel = (categoryId: string): string => {
  const category = categories.find(c => c.id === categoryId);
  return category?.label || categoryId;
};

export const getArticleById = (id: string): LegalArticle | undefined => {
  return legalArticles.find(article => article.id === id);
};

export const filterArticles = (categoryFilter: string, searchQuery: string): LegalArticle[] => {
  return legalArticles.filter(article => {
    const matchesCategory = categoryFilter === "all" || article.category === categoryFilter;
    const matchesSearch = searchQuery === "" || 
      article.title.toLowerCase().includes(searchQuery.toLowerCase()) ||
      article.lead.toLowerCase().includes(searchQuery.toLowerCase());
    return matchesCategory && matchesSearch;
  });
};

export const getRelatedArticles = (articleIds: string[]): LegalArticle[] => {
  return articleIds
    .map(id => getArticleById(id))
    .filter((article): article is LegalArticle => article !== undefined);
};
